#!/usr/bin/env python3
"""Generate target constants from the validated CrossState runtime contract."""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_CONTRACT = ROOT / "artifacts/generated/firewall_contract.json"

OUTPUTS = {
    "p4/firewall_constants.p4",
    "ebpf/firewall_constants.h",
}


def render_outputs(contract):
    if contract.get("format") != "crossstate-runtime-contract":
        raise ValueError("Unsupported runtime-contract format.")

    spec = contract.get("spec", {})
    table = spec.get("table", {})
    semantics = spec.get("semantics", {})
    runtime = contract.get("runtime_contract", {})

    slots = table.get("slots")
    buckets = table.get("buckets")
    timeout = table.get("idle_timeout_us")
    fields = spec.get("key_fields", [])
    state_codes = semantics.get("state_codes", {})
    runtime_codes = runtime.get("state_codes", {})

    if type(slots) is not int or slots <= 0 or slots & (slots - 1):
        raise ValueError("Table slots must be a positive power of two.")

    if type(buckets) is not int or buckets <= 0 or slots % buckets:
        raise ValueError("Buckets must be positive and divide slots evenly.")

    if type(timeout) is not int or not 0 < timeout < (1 << 48):
        raise ValueError("Timeout must fit the P4 u48 timestamp representation.")

    if not isinstance(fields, list) or not fields:
        raise ValueError("Contract must declare non-empty key_fields.")

    key_len = sum(field.get("bytes", 0) for field in fields)
    declared_key_len = runtime.get("flow_key", {}).get(
        "serialized_length_bytes"
    )

    if key_len != declared_key_len or key_len != 13:
        raise ValueError(
            f"Key length mismatch: fields={key_len}, "
            f"runtime contract={declared_key_len}, expected=13."
        )

    expected_states = {"NEW", "EST", "CLOSED"}
    if set(state_codes) != expected_states:
        raise ValueError("Contract must declare NEW, EST, and CLOSED state codes.")

    if state_codes != runtime_codes:
        raise ValueError("Specification and runtime state codes disagree.")

    if state_codes != {"NEW": 1, "EST": 2, "CLOSED": 3}:
        raise ValueError("Unsupported v1 firewall state-code mapping.")

    if any(type(code) is not int or not 0 <= code < 256
           for code in state_codes.values()):
        raise ValueError("State codes must fit the P4 bit<8> representation.")

    if semantics.get("flow_key", {}).get("encoding") != "network_byte_order":
        raise ValueError("Unsupported flow-key encoding.")

    if semantics.get("flow_key", {}).get("canonicalization") != (
        "sort_endpoints_by_ip_then_port"
    ):
        raise ValueError("Unsupported flow-key canonicalization.")

    timeout_semantics = semantics.get("timeout", {})
    runtime_timeout = runtime.get("timeout", {})

    if timeout_semantics.get("unit") != "us":
        raise ValueError("Unsupported timeout unit.")

    inclusive = timeout_semantics.get("boundary") == "inclusive"
    if runtime_timeout.get("live_when_elapsed_le_timeout") != inclusive:
        raise ValueError("Specification and runtime timeout boundaries disagree.")

    if runtime_timeout.get("expired_flow_behavior") != (
        timeout_semantics.get("expired_flow_behavior")
    ):
        raise ValueError("Specification and runtime expiry behavior disagree.")

    if table.get("collision") != "reject" or table.get("expiry") != "lazy":
        raise ValueError("Unsupported collision or expiry policy.")

    counter_width = runtime.get("counters", {}).get("width_bits")
    if counter_width != 64:
        raise ValueError("Unsupported counter width; expected 64 bits.")

    p4 = f"""/* Generated by scripts/generate_target_constants.py. DO NOT EDIT. */
#ifndef CROSSSTATE_FIREWALL_CONSTANTS_P4
#define CROSSSTATE_FIREWALL_CONSTANTS_P4

#define CS_SLOT_COUNT {slots}
#define CS_SLOT_COUNT_B32 32w{slots}
#define CS_BUCKET_COUNT {buckets}
#define CS_KEY_LEN {key_len}
#define CS_IDLE_TIMEOUT_US 48w{timeout}
#define CS_ST_NEW 8w{state_codes["NEW"]}
#define CS_ST_EST 8w{state_codes["EST"]}
#define CS_ST_CLOSED 8w{state_codes["CLOSED"]}

#endif
"""

    c_header = f"""/* Generated by scripts/generate_target_constants.py. DO NOT EDIT. */
#ifndef CROSSSTATE_FIREWALL_CONSTANTS_H
#define CROSSSTATE_FIREWALL_CONSTANTS_H

#define CS_SLOT_COUNT {slots}U
#define CS_BUCKET_COUNT {buckets}U
#define CS_KEY_LEN {key_len}U
#define CS_IDLE_TIMEOUT_US {timeout}ULL
#define CS_ST_NEW {state_codes["NEW"]}U
#define CS_ST_EST {state_codes["EST"]}U
#define CS_ST_CLOSED {state_codes["CLOSED"]}U
#define CS_COUNTER_WIDTH_BITS {counter_width}U

#endif
"""

    return {
        "p4/firewall_constants.p4": p4,
        "ebpf/firewall_constants.h": c_header,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--contract",
        type=Path,
        default=DEFAULT_CONTRACT,
        help="Path to the generated JSON runtime contract.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Check generated files without writing them.",
    )
    args = parser.parse_args()

    contract_path = args.contract
    if not contract_path.is_absolute():
        contract_path = ROOT / contract_path

    try:
        contract = json.loads(contract_path.read_text(encoding="utf-8"))
        outputs = render_outputs(contract)

        for relative_path in sorted(outputs):
            path = ROOT / relative_path
            expected = outputs[relative_path]

            if args.check:
                if not path.is_file():
                    raise ValueError(f"Generated file is missing: {relative_path}")
                actual = path.read_text(encoding="utf-8")
                if actual != expected:
                    raise ValueError(f"Generated file is stale: {relative_path}")
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(expected, encoding="utf-8")

            print(f"{'Checked' if args.check else 'Generated'}: {relative_path}")

    except Exception as exc:
        print(f"TARGET_CONSTANTS = FAIL\n{exc}", file=sys.stderr)
        return 1

    print("TARGET_CONSTANTS = PASS")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
